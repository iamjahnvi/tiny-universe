// color journey. Order is deliberate — cold blue depths descend through
// violet, cyan, magenta, ember reds, monochrome, into a luminous finale.

export const SCROLL = {
  introVh: 100,
  chapterVh: 230, // long dwell: approach → dominate → recede per galaxy
  outroVh: 140,
};

export function scrollGeometry() {
  const totalVh =
    SCROLL.introVh + CHAPTERS.length * SCROLL.chapterVh + SCROLL.outroVh;
  const travelVh = totalVh - 100;
  const centerOf = (i) =>
    (SCROLL.introVh + (i + 0.5) * SCROLL.chapterVh) / travelVh;
  return { totalVh, travelVh, centerOf };
}

